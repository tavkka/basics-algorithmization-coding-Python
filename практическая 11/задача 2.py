# на 100 рублей максимум можно купить: быков 10, коров 20, телят 200

for b in range(0, 11):
    for k in range(0, 21):
        for t in range(0, 201):
            if (b + k + t >= 1) and (10 * b + 5 * k + 0.5 * t == 100):
                print(f"Можно купить быков = {b}; коров = {k}; телят = {t}")